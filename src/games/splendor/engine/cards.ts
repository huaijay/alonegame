const BONUS_ORDER: readonly GemColor[] = ['red', 'green', 'blue', 'white', 'black'];

/** 完整基础版发展牌库：I 阶 40 张、II 阶 30 张、III 阶 20 张。 */
export const DEVELOPMENT_CARDS: DevelopmentCard[] = ROWS.map((row, index) => {
  const tier: Tier = index < 40 ? 1 : index < 70 ? 2 : 3;
  const [red, green, blue, white, black, colorIndex, points] = row;
  const cost: Gems = { red, green, blue, white, black };
  return { id: 'C' + String(index + 1).padStart(2, '0'), tier, bonus: BONUS_ORDER[colorIndex], points, cost };
});

